import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const picker = readFileSync(new URL('../src/page/ui/LanguagePicker.tsx', import.meta.url), 'utf8');
const styles = readFileSync(new URL('../src/page/ui/styles.ts', import.meta.url), 'utf8');
assert(!picker.includes('wa-translate-incoming-status'));
assert(!picker.includes('保存提醒 · 查看'));
assert(picker.includes('data-warning={warning ? "true" : "false"}'));
assert(picker.includes('aria-label={buttonLabel}'));
assert(picker.includes('收 {directionSymbol(incomingTarget)}'));
assert(picker.includes('发 {directionSymbol(outgoingTarget)}'));
assert(picker.includes('保存状态：{historyStatus || "暂无保存异常"}'));
assert(picker.includes('接收状态：{incomingError || incomingLabel}'));
assert(styles.includes('overflow-wrap: anywhere'));
assert(picker.includes('document.body,'));
assert(styles.includes('.wa-translate-tab-panel { flex:1; min-height:0; overflow:auto;'));
const require = createRequire(import.meta.url);
const esbuild = createRequire(require.resolve('vite'))('esbuild');
const result = esbuild.buildSync({entryPoints:['src/page/ui/picker-indicator.ts'],bundle:true,platform:'node',format:'cjs',write:false});
const api = {exports:{}};
new Function('module','exports',result.outputFiles[0].text)(api,api.exports);
const {directionSymbol,diagnosticWarning} = api.exports;
assert.equal(directionSymbol('zh-CN'),'简中');
assert.equal(directionSymbol('en'),'EN');
assert.equal(directionSymbol('fr'),'FR');
assert.equal(directionSymbol(null),'关');
assert.equal(directionSymbol('invalid'),'关');
assert.equal(diagnosticWarning([{stage:'failed_network'},{stage:'preview_hidden'}]),true);
assert.equal(diagnosticWarning([{stage:'failed_network'},{stage:'preview_ready'}]),false);
assert.equal(diagnosticWarning([{stage:'timeout_bubble'}]),true);
assert.equal(diagnosticWarning([{stage:'failed_cancelled'}]),false);
console.log('PASS Picker shows direction symbols and warning icon only; full logs wrap in portal (source-contract + indicator tests)');
